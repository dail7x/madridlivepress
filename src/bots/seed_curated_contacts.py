def seed_curated():
    print("🚀 Sincronizando contactos base de prensa clasificados en Directus...")
    client = DirectusPressClient()
    existing = client.get_existing_emails()
    print(f"Contactos existentes en Directus: {len(existing)}")

    inserted = 0
    for contact in CURATED_CONTACTS:
        email = contact["email"].lower().strip()
        if email in existing:
            # print(f"Contacto ya existe: {email}")
            continue

        success = client.save_contact(contact)
        if success:
            inserted += 1
            existing.add(email)
            print(f"✅ Guardado: {contact['medio']} - {email} [{contact['categoria_principal']}]")
        else:
            print(f"❌ Error al guardar: {email}")

    print(f"\n🎉 Finalizado: {inserted} contactos nuevos insertados en Directus.")

